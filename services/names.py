_TOKEN_SPLIT = re.compile(r"[\s.,/\\|_()\[\]{}«»\"'’`+*-]+")
_BAD_CHAR = re.compile(r"[0-9@#№$%^&=~<>:;!?]")
_CYRILLIC = re.compile(r"^[а-яё]+$")


def _tokens(raw: str) -> list[str]:
    lowered = raw.strip().lower().replace("ё", "е")
    return [t for t in _TOKEN_SPLIT.split(lowered) if t]


def classify_name(raw: str | None) -> str:
    """PERSON - имя точно человеческое, COMPANY - точно вывеска, иначе UNKNOWN."""
    if not raw or not raw.strip():
        return UNKNOWN
    if _BAD_CHAR.search(raw):
        return COMPANY
    tokens = _tokens(raw)
    if not tokens or len(tokens) > 3:
        return COMPANY
    if any(len(t) > 20 for t in tokens):
        return COMPANY
    if any(t in COMPANY_ABBR for t in tokens):
        return COMPANY
    if any(t.startswith(stem) for t in tokens for stem in COMPANY_STEMS):
        return COMPANY
    # Имя может стоять и вторым: «Ткачев Сергей».
    if any(t in FIRST_NAMES for t in tokens):
        return PERSON
    # Ни имени, ни вывески: одно кириллическое слово вроде «Вектор» - непонятно.
    if all(_CYRILLIC.match(t) for t in tokens):
        return UNKNOWN
    return COMPANY


def person_first_name(raw: str | None) -> str | None:
    """Само имя из профиля: из «Ткачев Сергей» нужен «Сергей», а не фамилия."""
    if classify_name(raw) != PERSON:
        return None
    original = [t for t in _TOKEN_SPLIT.split((raw or "").strip()) if t]
    for word, norm in zip(original, _tokens(raw or "")):
        if norm in FIRST_NAMES:
            return word if word[:1].isupper() else word.capitalize()
    return None


def address_hint(raw: str | None) -> str | None:
    """Подсказка боту, спрашивать имя или уже обращаться по имеющемуся."""
    verdict = classify_name(raw)
    if verdict == PERSON:
        name = person_first_name(raw)
        return (
            f"имя клиента уже известно из профиля - {name}. "
            "Не спрашивай, как к нему обращаться, обращайся по имени"
        )
    if verdict == COMPANY:
        return (
            f"в профиле указано «{(raw or '').strip()}» - это вывеска, а не имя. "
            "Имя можно спросить один раз, вместе с номером или после него"
        )
    return None
